let current = 0;

function startQuest() {
  current = Math.floor(Math.random() * divisionQuestions.length);
  document.getElementById("status").textContent = "";
  document.getElementById("restart").style.display = "none";
  loadQuestion();
}

function loadQuestion() {
  const q = divisionQuestions[current];
  document.getElementById("question").textContent = q.question;

  const optionsBox = document.getElementById("options");
  optionsBox.innerHTML = "";

  q.options.forEach(opt => {
    const btn = document.createElement("button");
    btn.textContent = opt;
    btn.onclick = () => checkAnswer(opt);
    optionsBox.appendChild(btn);
  });
}

function checkAnswer(selected) {
  const correct = divisionQuestions[current].correct;
  const status = document.getElementById("status");

  if (selected === correct) {
    status.textContent = "🔓 Correct! Gate Unlocked!";
    status.style.color = "green";
  } else {
    status.textContent = "❌ Wrong! Gate stays locked.";
    status.style.color = "red";
  }

  document.getElementById("restart").style.display = "inline-block";
}

window.onload = startQuest;
